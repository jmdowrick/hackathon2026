"""Import a KcsA structure from the PDB and MEASURE what we had assumed.

Three things in the KcsA model were parameterised and can instead be read off
a 2.0 A structure:

  * the site positions along the pore (the K+ ions are RESOLVED in 1K4C)
  * the pore axis and origin (from the C4 ring of the selectivity filter)
  * the pore radius profile, which sets the electrical distances

Nothing here needs mdtraj or a force field: a PDB is a text file and the
tetramer comes from the BIOMT operators in REMARK 350.

WHY THE TETRAMER MATTERS. 1K4C deposits ONE KcsA subunit (chain C) plus two
Fab chains; the channel is generated by crystallographic symmetry. Measuring a
pore radius from the single deposited chain would see only a quarter of the
wall and report a pore several angstroms too wide.
"""

from __future__ import annotations

import os
import urllib.request
from dataclasses import dataclass, field

import numpy as np

RCSB = "https://files.rcsb.org/download/{}.pdb"

# KcsA selectivity filter signature, confirmed against 1K4C chain C
FILTER_RESIDUES = (75, 76, 77, 78, 79)        # Thr Val Gly Tyr Gly


def fetch(pdb_id, cache_dir="data"):
    """Download a PDB entry, cached. No login, no API key."""
    os.makedirs(cache_dir, exist_ok=True)
    path = os.path.join(cache_dir, f"{pdb_id.upper()}.pdb")
    if not os.path.exists(path):
        urllib.request.urlretrieve(RCSB.format(pdb_id.upper()), path)
    return path


@dataclass
class Structure:
    xyz: np.ndarray                 # (n, 3)
    element: np.ndarray             # (n,) str
    resname: np.ndarray
    resseq: np.ndarray
    chain: np.ndarray
    name: np.ndarray
    is_hetatm: np.ndarray
    meta: dict = field(default_factory=dict)

    def select(self, **kw):
        m = np.ones(len(self.xyz), dtype=bool)
        for k, v in kw.items():
            col = getattr(self, k)
            m &= np.isin(col, np.atleast_1d(v))
        return m


def read_pdb(path, keep_chains=None, models=(1,)):
    """Minimal PDB reader. Returns a Structure plus the BIOMT operators."""
    xyz, el, rn, rs, ch, nm, het = [], [], [], [], [], [], []
    biomt, cur = {}, None
    model = 1

    for line in open(path):
        if line.startswith("MODEL"):
            try:
                model = int(line[10:14])
            except ValueError:
                model = 1
        elif line.startswith("REMARK 350   BIOMT"):
            try:
                row = int(line[18:19])
                op = int(line[19:23])
                vals = [float(line[24:33]), float(line[34:43]),
                        float(line[44:53]), float(line[58:68])]
                biomt.setdefault(op, np.zeros((3, 4)))[row - 1] = vals
            except (ValueError, IndexError):
                pass
        elif line.startswith(("ATOM", "HETATM")):
            if models and model not in models:
                continue
            c = line[21]
            if keep_chains is not None and c not in keep_chains:
                continue
            # skip alternate locations other than the first
            alt = line[16]
            if alt not in (" ", "A"):
                continue
            xyz.append([float(line[30:38]), float(line[38:46]),
                        float(line[46:54])])
            e = line[76:78].strip() or line[12:16].strip()[:1]
            el.append(e.upper())
            rn.append(line[17:20].strip())
            rs.append(int(line[22:26]))
            ch.append(c)
            nm.append(line[12:16].strip())
            het.append(line.startswith("HETATM"))

    s = Structure(np.array(xyz), np.array(el), np.array(rn), np.array(rs),
                  np.array(ch), np.array(nm), np.array(het),
                  meta={"path": path, "n_biomt": len(biomt)})
    ops = [biomt[k] for k in sorted(biomt)] if biomt else [np.hstack(
        [np.eye(3), np.zeros((3, 1))])]
    return s, ops


def apply_biomt(s: Structure, ops, which=None):
    """Expand to the biological assembly.

    `which` selects a subset of operators -- for 1K4C the deposited assembly
    is dodecameric (channel plus Fabs), and the four operators that generate
    the C4 channel are the ones that matter here.
    """
    ops = [ops[i] for i in which] if which is not None else ops
    X, E, RN, RS, CH, NM, HE = [], [], [], [], [], [], []
    for k, op in enumerate(ops):
        R, t = op[:, :3], op[:, 3]
        X.append(s.xyz @ R.T + t)
        E.append(s.element); RN.append(s.resname); RS.append(s.resseq)
        CH.append(np.array([f"{c}{k}" for c in s.chain]))
        NM.append(s.name); HE.append(s.is_hetatm)
    return Structure(np.concatenate(X), np.concatenate(E), np.concatenate(RN),
                     np.concatenate(RS), np.concatenate(CH), np.concatenate(NM),
                     np.concatenate(HE), meta={**s.meta, "n_copies": len(ops)})


def pore_frame(s: Structure, filter_residues=FILTER_RESIDUES):
    """Pore axis and origin from the filter's C4 ring.

    Origin: centroid of the Thr75 CA atoms of the four subunits.
    Axis:   the direction of least variance of that ring, i.e. the C4 axis,
            oriented so +z points extracellular (away from the protein's bulk).
    """
    m = s.select(name="CA", resseq=list(filter_residues)) & ~s.is_hetatm
    if m.sum() < 4:
        raise ValueError(f"only {m.sum()} filter CA atoms; expand the assembly")
    thr = s.select(name="CA", resseq=filter_residues[0]) & ~s.is_hetatm
    ring = s.xyz[thr] if thr.sum() >= 3 else s.xyz[m]

    origin = ring.mean(axis=0)
    _, _, vt = np.linalg.svd(ring - origin)
    axis = vt[-1] / np.linalg.norm(vt[-1])

    # orient: the extracellular side is the one the filter's N-terminal
    # residues point away from; use the protein centroid as the reference
    prot = s.xyz[~s.is_hetatm].mean(axis=0)
    if np.dot(origin - prot, axis) < 0:
        axis = -axis
    return origin, axis, int(thr.sum())


def ion_sites(s: Structure, origin, axis, ion="K", max_radius_A=2.5):
    """Positions of resolved ions along the pore axis.

    Only ions within max_radius_A of the axis are kept, so surface-bound ions
    do not masquerade as filter sites.
    """
    m = s.select(resname=ion) & s.is_hetatm
    if not m.any():
        return np.array([]), np.array([])
    P = s.xyz[m] - origin
    z = P @ axis
    r = np.linalg.norm(P - np.outer(z, axis), axis=1)
    keep = r <= max_radius_A
    zs, rs = z[keep], r[keep]
    order = np.argsort(zs)
    zs, rs = zs[order], rs[order]

    # Ions ON the C4 axis are mapped onto themselves by every BIOMT operator,
    # so the assembly contains four identical copies of each. Collapse them,
    # or every site appears four times and the spacings come out as zeros.
    if zs.size:
        uniq_z, uniq_r = [zs[0]], [rs[0]]
        for a, b in zip(zs[1:], rs[1:]):
            if a - uniq_z[-1] > 0.5:
                uniq_z.append(a); uniq_r.append(b)
        zs, rs = np.array(uniq_z), np.array(uniq_r)
    return zs, rs


# Solvent and ion residue names. HETATM is NOT a synonym for "not protein":
# gramicidin's D-residues (DLE, DVA) and its formyl/ethanolamine caps are all
# HETATM in 1JNO -- half the atoms -- and dropping them doubles the apparent
# pore radius at the channel entrances.
SOLVENT_AND_IONS = ("HOH", "WAT", "DOD", "SOL", "K", "NA", "CL", "CA", "MG",
                    "RB", "CS", "LI", "ZN", "SO4", "PO4")


def non_solvent(s: Structure):
    """Mask of every atom that is not water or a simple ion."""
    return ~np.isin(s.resname, SOLVENT_AND_IONS)


def radius_profile(s: Structure, origin, axis, z_edges, probe_A=1.4,
                   heavy_only=True, wall_mask=None):
    """Pore radius per slab: minimum clearance to a protein heavy atom.

    wall_mask selects the atoms that line the pore. The default, ATOM records
    only, is right for 1K4C (whose HETATM are ions, water and lipid) and wrong
    for any peptide with non-standard residues; pass non_solvent(s) there.
    """
    m = ~s.is_hetatm if wall_mask is None else np.asarray(wall_mask, bool)
    if heavy_only:
        m &= s.element != "H"
    P = s.xyz[m] - origin
    z = P @ axis
    r = np.linalg.norm(P - np.outer(z, axis), axis=1)

    z_edges = np.asarray(z_edges, float)
    idx = np.digitize(z, z_edges) - 1
    out = np.full(len(z_edges) - 1, np.nan)
    for b in range(len(out)):
        sel = idx == b
        if sel.any():
            out[b] = max(float(r[sel].min()) - probe_A, 0.05)
    return out


def load_kcsa(pdb_id="1K4C", cache_dir="data", chain="C",
              filter_residues=FILTER_RESIDUES, n_slabs=90,
              z_range=(-22.0, 16.0), probe_A=1.4):
    """One call: structure -> pore frame, measured ion sites, radius profile.

    Returns everything the KcsA model had been assuming, measured instead.
    """
    path = fetch(pdb_id, cache_dir)
    s1, ops = read_pdb(path, keep_chains=[chain])
    # the four operators that generate the C4 channel
    s4 = apply_biomt(s1, ops, which=list(range(min(4, len(ops)))))

    origin, axis, n_ring = pore_frame(s4, filter_residues)
    z_ions, r_ions = ion_sites(s4, origin, axis)

    edges = np.linspace(z_range[0], z_range[1], n_slabs + 1)
    centres = 0.5 * (edges[1:] + edges[:-1])
    rad = radius_profile(s4, origin, axis, edges, probe_A)

    return {
        "pdb_id": pdb_id.upper(), "path": path,
        "n_operators": len(ops), "n_filter_ring_atoms": n_ring,
        "origin": origin, "axis": axis,
        "ion_z_A": z_ions, "ion_r_A": r_ions,
        "radius_z_A": centres, "radius_A": rad,
        "note": ("Site positions are the RESOLVED K+ ions; the axis and "
                 "origin come from the filter C4 ring; the radius profile is "
                 "the minimum clearance to a protein heavy atom per slab. "
                 "The tetramer is built from REMARK 350 BIOMT -- measuring "
                 "from the single deposited chain would report a pore several "
                 "angstroms too wide."),
    }
